<h1>Compact &amp; Fast MVC Framework</h1>
<p class="lead">SimpleMVC is a straightforward PHP implementation of the MVC pattern with no runtime dependencies.</p>

<hr>

<h3>1. Prerequisites</h3>
<ul>
    <li><a href="https://www.php.net/supported-versions.php" target="_blank" rel="noopener">PHP 8.3</a> or higher.</li>
    <li><a href="https://getcomposer.org" target="_blank" rel="noopener">Composer</a> for autoloading.</li>
    <li>A web server that can rewrite URLs (Apache, Nginx, Caddy, IIS) &mdash; or PHP's built-in server for development.</li>
</ul>

<h3>2. Install</h3>
<p>Clone the repository and run <code>composer install</code>.</p>

<h3>3. Run</h3>
<p>Point your web server's document root at the <code>public/</code> directory, or for development run:</p>
<pre><code>php -S localhost:8000 -t public public/index.php</code></pre>

<h3>4. Let's go!</h3>
<p>Experiment with the default setup or check the <a href="/Home/Docs">docs</a>. Happy coding!</p>
